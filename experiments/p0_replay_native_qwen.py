"""P0 replay on real pretrained Qwen2.5-VL QKV (no pretrained weights required to replay).

Compare three things, without confusing their semantics:
1) Native eager Attention output vs independent dense factual Attention in BF16.
2) CFPO-style CMVE operator on real post-M-RoPE QKV in BF16.
3) FP32 transformed QKV: Dense CMVE vs current FP32 Triton+custom backward.

This is operator parity on native pretrained states, NOT the original patched CFPO
end-to-end forward. BF16 support in Triton remains unimplemented. Hard-mask
decision flips are separately reported, never silently treated as strict parity.
"""
from __future__ import annotations
import argparse
import json
from pathlib import Path
import sys
import torch

ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from tools.replay_official_fixture import reference_official_dense
from tools.p0_official_cmve_oracle import official_dense_cfpo, UPSTREAM_COMMIT, UPSTREAM_BLOB_SHA
from reference.cfpo_reference import dense_cfpo
from kernels.triton_backward_gather import flashcf_gather


def read_fixture(path):
    # Only load files generated by our own capture script on Tang.
    obj=torch.load(path,map_location="cpu",weights_only=True)
    for k in ("q","k","v","image_spans","native_output"):
        if k not in obj:raise ValueError(f"fixture missing {k}")
    q,k,v=(obj[n] for n in ("q","k","v"))
    if q.ndim!=4 or q.shape!=k.shape or k.shape!=v.shape:
        raise ValueError("Q/K/V should have GQA-expanded [B,H,L,D] shape")
    return obj


def run(path,device):
    obj=read_fixture(path)
    q,k,v=(obj[key].to(device).contiguous() for key in ("q","k","v"))
    B,H,L,D=q.shape
    spans=obj["image_spans"]
    image_pos=[[{"image_token_start":st,"image_token_end":en} for st,en in group]
               for group in spans]
    mask=obj.get("additive_mask")
    if mask is None:raise RuntimeError("Cannot assert official mask semantics: native mask absent")
    mask=mask.to(device)
    if mask.ndim!=4 or mask.shape[-2:]!=(L,L):
        raise RuntimeError(f"Expected 4D causal mask, got {list(mask.shape)}")
    allowed=mask[:,0].to(torch.float32)>-10000
    expected_causal=torch.arange(L,device=device)[:,None]>=torch.arange(L,device=device)[None,:]
    simple_causal=bool((allowed==expected_causal[None]).all())
    native=obj["native_output"].to(device)
    official_bf16,p,selected_mask=reference_official_dense(
        q,k,v,mask,image_pos,thres_mode="high",mean_mode="image",
        attention_dropout=0,noise=False,sliding_window=None)
    exact_bf16, exact_normal, exact_mask, _ = official_dense_cfpo(
        q,k,v,mask,spans,thres_mode="high",mean_mode="image")
    original_mask_equal = bool(torch.equal(selected_mask,exact_mask))
    bf16_operator_error=float((official_bf16-exact_bf16).float().abs().max())
    if not original_mask_equal:
        raise AssertionError("Independent BF16 mask differs from pinned original CFPO function")
    # The unmodified native eager output has shape [B,L,H,D].
    native=native.transpose(1,2) if native.shape==(B,L,H,D) else native
    native_factual_err=(p@v-native).float().abs().max().item()

    result=dict(
        layer=obj["layer"],shape=[B,H,L,D],
        original_dtype=str(q.dtype),native_4d_causal_mask=simple_causal,
        native_factual_vs_independent_bf16_abs=native_factual_err,
        official_bf16_cmve_selection_fraction=float(selected_mask.float().mean()),
        exact_original_cfpo_mask_equal=original_mask_equal,
        exact_original_cfpo_bf16_operator_max_abs=bf16_operator_error,
        original_cfpo_source_commit=UPSTREAM_COMMIT,
        original_cfpo_source_blob=UPSTREAM_BLOB_SHA,
        operator_provenance="Unmodified CMVE helper functions AST-loaded from pinned CFPO Git source; native Qwen2.5 weights",
        original_model_cmve_forward_tested=False,
    )

    if simple_causal:
        qc,kc,vc=(x.float().detach().requires_grad_(True) for x in (q,k,v))
        weight=torch.randn_like(qc)
        dense=dense_cfpo(qc,kc,vc,spans,thres_mode="high",mean_mode="image")
        upstream_fp32,_,upstream_mask_fp32,_=official_dense_cfpo(
            qc,kc,vc,mask.float(),spans,thres_mode="high",mean_mode="image")
        result["independent_vs_upstream_fp32_max_abs"]=float((dense-upstream_fp32).abs().max())
        # FP32 is an adapted input path, not a BF16 native-kernel equivalence claim.
        try:
            triton=flashcf_gather(qc,kc,vc,spans,thres_mode="high",
                                  mean_mode="image",block_k=32)
            dr=torch.autograd.grad((dense*weight).sum(),(qc,kc,vc),retain_graph=True)
            gr=torch.autograd.grad((triton*weight).sum(),(qc,kc,vc))
            result.update(
                triton_fp32_forward_max_abs=(dense-triton).abs().max().item(),
                triton_fp32_forward_rmse=((dense-triton).square().mean().sqrt()).item(),
                triton_fp32_grad_max_abs=max((x-y).abs().max().item() for x,y in zip(dr,gr)),
                triton_fp32_strict_parity=bool((dense-triton).abs().max().item()<2e-4 and
                                               max((x-y).abs().max().item() for x,y in zip(dr,gr))<1e-3),
            )
        except Exception as e:
            result["triton_fp32_error"]=type(e).__name__+": "+str(e)[:200]
    else:
        result["triton_fp32_status"]="SKIPPED: native attention mask is not simple causal"
    print(json.dumps(result,indent=2),flush=True)
    return result


if __name__=="__main__":
    p=argparse.ArgumentParser()
    p.add_argument("files",nargs="+",type=Path)
    p.add_argument("--summary",type=Path,default=ROOT/"experiments"/"results"/"p0_real_qkv_parity_local.json")
    args=p.parse_args()
    if not torch.cuda.is_available():
        raise RuntimeError("Expected GPU for real BF16 replay")
    results=[run(f,"cuda") for f in args.files]
    args.summary.parent.mkdir(parents=True,exist_ok=True)
    args.summary.write_text(json.dumps({"layers":results},indent=2)+"\n")
